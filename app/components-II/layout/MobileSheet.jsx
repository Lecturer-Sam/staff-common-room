// 5. src/components/layout/MobileSheet.jsx — Hamburger Drawer
import { useEffect } from "react";
import { NavLink } from "react-router-dom";

const navItems = [
  { to: "/", label: "Dashboard", icon: GridIcon },
  { to: "/projects", label: "Projects", icon: FolderIcon },
  { to: "/members", label: "Members", icon: UsersIcon },
  { to: "/documents", label: "Documents", icon: FileIcon },
  { to: "/calendar", label: "Calendar", icon: CalendarIcon },
];

export default function MobileSheet({ isOpen, onClose }) {
  // Lock body scroll when open
  useEffect(() => {
    if (isOpen) {
      document.body.style.overflow = "hidden";
    } else {
      document.body.style.overflow = "";
    }
    return () => {
      document.body.style.overflow = "";
    };
  }, [isOpen]);

  if (!isOpen) return null;

  return (
    <div className="fixed inset-0 z-50 lg:hidden" onClick={onClose}>
      {/* Backdrop */}
      <div className="absolute inset-0 bg-black/40 animate-fade-in" />

      {/* Sheet */}
      <div
        className="absolute left-0 top-0 bottom-0 w-72 bg-navbar-bg p-4 overflow-y-auto animate-slide-in"
        onClick={(e) => e.stopPropagation()}
      >
        {/* Header */}
        <div className="flex items-center justify-between mb-6">
          <div className="flex items-center gap-3">
            <div className="w-9 h-9 bg-app-primary rounded-xl flex items-center justify-center">
              <ConsortiumLogo />
            </div>
            <div className="font-bold text-[0.95rem]">Consortium</div>
          </div>
          <button
            onClick={onClose}
            className="p-2 rounded-xl hover:bg-black/5 transition-colors"
          >
            <XIcon className="w-5 h-5" />
          </button>
        </div>

        {/* Navigation */}
        <nav className="flex flex-col gap-1">
          {navItems.map((item) => (
            <NavLink
              key={item.to}
              to={item.to}
              end={item.to === "/"}
              onClick={onClose}
              className={({ isActive }) =>
                `flex items-center gap-3 p-3 rounded-xl text-[0.9rem] font-medium transition-colors ${
                  isActive
                    ? "bg-app-primary/10 text-app-primary"
                    : "text-app-text-secondary hover:bg-black/5 hover:text-app-text"
                }`
              }
            >
              <item.icon className="w-5 h-5" />
              {item.label}
            </NavLink>
          ))}
        </nav>
      </div>
    </div>
  );
}

